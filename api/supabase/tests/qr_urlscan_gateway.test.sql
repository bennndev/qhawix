begin;
select plan(17);
select is(public.qr_gateway_get_config()->>'provider', 'urlscan_v1', 'gateway uses urlscan');
select is(public.qr_gateway_get_config()->>'schemaVersion', '2', 'gateway uses contract v2');
select is(public.qr_gateway_get_config()->>'perHourLimit', '50', 'hourly limit is explicit');
select ok(not has_function_privilege('anon', 'public.qr_gateway_get_config()', 'EXECUTE'), 'anon cannot read privileged config');
select ok(not has_function_privilege('authenticated', 'public.qr_consume_reputation_quota()', 'EXECUTE'), 'clients cannot consume privileged quota RPC');
select ok(has_function_privilege('service_role', 'public.qr_consume_reputation_quota()', 'EXECUTE'), 'gateway can consume quota');
select ok(not has_function_privilege('anon', 'public.qr_get_reputation_match(text)', 'EXECUTE'), 'anon cannot read cache');
select ok(not has_function_privilege('authenticated', 'public.qr_store_reputation_match(text,text[],timestamptz,timestamptz)', 'EXECUTE'), 'clients cannot forge matches');
select ok(not public.qr_store_reputation_match(repeat('a', 64), array['MALWARE'], now(), now() + interval '1 minute'), 'old provider category is rejected');
select ok(public.qr_store_reputation_match(repeat('b', 64), array['URLSCAN_PHISHING'], now(), now() + interval '1 minute'), 'bounded urlscan match can be cached');
select ok(not public.qr_store_reputation_match(repeat('c', 64), array['URLSCAN_PHISHING'], now(), now() + interval '1 hour'), 'excessive match lifetime is rejected');
select ok((select relrowsecurity from pg_class where oid = 'private.qr_reputation_match_cache'::regclass), 'cache retains RLS');
delete from private.qr_gateway_quota_windows;
update private.qr_gateway_config set per_minute_limit = 2;
select ok((public.qr_consume_reputation_quota()->>'allowed')::boolean, 'first request consumes quota');
select ok((public.qr_consume_reputation_quota()->>'allowed')::boolean, 'second request consumes quota');
select is(public.qr_consume_reputation_quota()->>'code', 'rate_limited', 'minute quota blocks the third request');
delete from private.qr_gateway_quota_windows where bucket = 'minute';
update private.qr_gateway_config set per_hour_limit = 2;
select is(public.qr_consume_reputation_quota()->>'code', 'rate_limited', 'hour quota remains enforced after minute reset');
update private.qr_gateway_config set per_minute_limit = 100, per_hour_limit = 100, per_day_limit = 1;
select is(public.qr_consume_reputation_quota()->>'code', 'quota_exhausted', 'day quota remains enforced');
select * from finish();
rollback;
